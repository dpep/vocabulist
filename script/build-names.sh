#!/usr/bin/env bash
# Regenerate data/names.txt and data/nicknames.txt.
#
# The output is committed, so a build needs no network; this only runs when
# the tables are being changed or refreshed.
#
# SOURCES AND LICENSES
#
# - Given names: US Census 1990, `dist.male.first` and `dist.female.first` —
#   each name's share of the male or female population. Public domain (a
#   work of the US federal government).
# - Surnames: US Census 2010 surname table — each surname's count of people.
#   Public domain, likewise.
# - Nicknames: carltonnorthern/nicknames `names.csv`, Apache-2.0. The license
#   is reproduced in data/COPYING.names; the change made here is lowercasing
#   and reordering the pairs.
#
# WHY THESE
#
# Both Census tables measure the same thing — the share of people who bear a
# name — so a given name and a surname sit on one scale, which is what lets
# `Mott` the surname and `Owen` the given name be compared at all. SSA birth
# counts would cover names popular after 1990 (`Jayden`, `Liam`), but ssa.gov
# refuses scripted downloads; a name missing here falls back to SCOWL's
# proper names, as before.
#
# WHAT IS KEPT, AND HOW COARSELY
#
# Every given name (the 1990 list stops at 0.001% of one sex already), and
# surnames borne by at least MIN_SURNAME people, about ten per million. The
# floor halves the table and keeps most of what it is for: of the real names
# one edit from a common given name, it keeps 5,288 of the 6,388 a floor of
# a thousand would. Lower down the table is thick with spelling variants
# (`Sara` and `Sarah` are each about a thousand people as surnames). Shares are per million people, to two significant figures:
# the 1990 percentages carry three decimals, and nothing this tool decides
# turns on a third digit.
set -euo pipefail

MIN_SURNAME="${MIN_SURNAME:-3000}"
NICKNAMES_REV="${NICKNAMES_REV:-master}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

census=https://www2.census.gov/topics/genealogy
echo "fetching Census given names and surnames..."
curl -sSfL -o "$WORK/male" "$census/1990surnames/dist.male.first"
curl -sSfL -o "$WORK/female" "$census/1990surnames/dist.female.first"
curl -sSfL -o "$WORK/surnames.zip" "$census/2010surnames/names.zip"
unzip -q -o "$WORK/surnames.zip" Names_2010Census.csv -d "$WORK"
echo "fetching nicknames ($NICKNAMES_REV)..."
curl -sSfL -o "$WORK/nicknames.csv" \
    "https://raw.githubusercontent.com/carltonnorthern/nicknames/$NICKNAMES_REV/names.csv"

# `<name>\tg\t<per million>` and `<name>\ts\t<per million>`, unrounded.
{
    # A per-sex percent is half the population's share: (pm + pf) / 2.
    awk '{ printf "%s\tg\t%.6f\n", tolower($1), $2 * 5000 }' "$WORK/male" "$WORK/female"
    # prop100k is per hundred thousand; the floor is applied to the count.
    awk -F, -v min="$MIN_SURNAME" 'NR > 1 && $3 >= min && $1 ~ /^[A-Z]+$/ {
        printf "%s\ts\t%.6f\n", tolower($1), $4 * 10
    }' "$WORK/Names_2010Census.csv"
} >"$WORK/shares"

OUT="$ROOT/data/names.txt"
{
    echo "# Generated by script/build-names.sh; see it for sources and licenses."
    echo "# Do not edit by hand. Sorted <name>\\t<given>\\t<surname>: the share of"
    echo "# US people bearing the name, per million, to two significant figures;"
    echo "# empty where the name is not one of that kind."
    awk -F'\t' '
        # Two significant figures, printed without an exponent.
        function sig2(x,   m) {
            if (x == "") return ""
            m = 1
            while (x >= 100 * m) m *= 10
            while (x < 10 * m) m /= 10
            x = int(x / m + 0.5) * m
            return (x >= 10) ? sprintf("%d", x) : sprintf("%.*f", (x >= 1) ? 1 : 2, x)
        }
        { if ($2 == "g") given[$1] += $3; else surname[$1] = $3; seen[$1] = 1 }
        END { for (n in seen) printf "%s\t%s\t%s\n", n, sig2(given[n]), sig2(surname[n]) }
    ' "$WORK/shares" | LC_ALL=C sort -k1,1
} >"$OUT"
echo "wrote $OUT: $(grep -cv '^#' "$OUT") names, $(du -h "$OUT" | cut -f1)"

OUT="$ROOT/data/nicknames.txt"
{
    echo "# Generated by script/build-names.sh from carltonnorthern/nicknames"
    echo "# (Apache-2.0, see data/COPYING.names). Do not edit by hand."
    echo "# Sorted <nickname>\\t<full name>, one pair a line."
    tr -d "\r" <"$WORK/nicknames.csv" | awk -F, 'NR > 1 && $2 == "has_nickname" && $1 ~ /^[a-z]+$/ && $3 ~ /^[a-z]+$/ {
        printf "%s\t%s\n", $3, $1
    }' | LC_ALL=C sort -u
} >"$OUT"
echo "wrote $OUT: $(grep -cv '^#' "$OUT") pairs, $(du -h "$OUT" | cut -f1)"
